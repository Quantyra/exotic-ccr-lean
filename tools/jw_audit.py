"""Generate and inspect the bounded Jacobian-Weyl declaration audit.

This program never invokes Lean and never issues a manuscript certificate.
Verification needs both Lean output and the independent compiler runner's
terminal receipt, bound to the exact source manifest, scope, and audit file.
"""

