def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    gen = commands.add_parser("generate", help="Generate audit source and immutable scope JSON")
    gen.add_argument("--claim-map", type=Path, default=Path("certification/claim-map.json"))
    gen.add_argument("--output", type=Path, default=Path("checks/JacobianWeylAudit.lean"))
    gen.add_argument("--scope-out", type=Path, required=True)
    gen.add_argument("--extra-import", action="append", default=[])
    gen.add_argument("--extra-declaration", action="append", default=[])
    check = commands.add_parser("verify", help="Verify terminal evidence and exact declaration scope")
    for name in ("source-root", "scope", "manifest", "receipt", "log", "output"):
        check.add_argument("--" + name, type=Path, required=True)
    commands.add_parser("self-test", help="Run local Python parser fixtures without Lean")
    args = parser.parse_args(argv)
    try:
        result = generate(args) if args.command == "generate" else verify(args) if args.command == "verify" else self_test()
        if args.command == "verify":
            atomic_write(args.output, json_bytes(result))
            result = {key: value for key, value in result.items() if key != "declarations"}
        print(json.dumps(result, ensure_ascii=False, sort_keys=True))
        return 0
    except (AuditError, OSError, UnicodeError, json.JSONDecodeError, KeyError, TypeError, AssertionError) as exc:
        failure = {"schema": "jw-audit-result-v1", "audit_status": "FAIL",
                   "certificate_issued": False, "error": str(exc)}
        if args.command == "verify":
            try:
                atomic_write(args.output, json_bytes(failure))
            except (OSError, AuditError):
                pass
        print(json.dumps(failure, ensure_ascii=False, sort_keys=True), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
